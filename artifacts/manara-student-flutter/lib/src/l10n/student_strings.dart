  /// Looks a key up in the language currently chosen.
  static String of(String key) {
    if (!StudentSettings.isArabic) {
      final english = _en[key];
      if (english != null) return english;
    }
    return _ar[key] ?? key;
  }

  /// The same, with `{name}` placeholders filled in.
  ///
  /// Many of the app's strings carry a number or a title inside them —
  /// "المستوى 3", "الكلمة 2 من 5". Those cannot be plain map entries,
  /// and splitting them into fragments to concatenate would break in
  /// English, where the pieces fall in a different order. A placeholder
  /// keeps each language's sentence whole and lets the word order differ.
  static String format(String key, Map<String, Object?> values) {
    var text = of(key);
    for (final entry in values.entries) {
      text = text.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return text;
  }

  /// Every key defined, for tests that check the two tables agree.
  @visibleForTesting
  static Iterable<String> get keys => _ar.keys;

  @visibleForTesting
  static Iterable<String> get englishKeys => _en.keys;

  /// The `{placeholder}` names a key expects, in the given table.
  @visibleForTesting
  static Set<String> placeholdersIn(String key, {required bool english}) {
    final text = (english ? _en[key] : _ar[key]) ?? '';
    return RegExp(r'\{(\w+)\}')
        .allMatches(text)
        .map((match) => match.group(1)!)
        .toSet();
  }
}

/// Shorthand so call sites read as text rather than as lookups.
String tr(String key) => StudentStrings.of(key);

/// Shorthand for a string with `{placeholders}`.
String trf(String key, Map<String, Object?> values) =>
    StudentStrings.format(key, values);
