import 'package:flutter/gestures.dart';

/// هل كانت هذه اللمسةُ لمسةً، أم بدايةَ تمرير؟
///
/// ── لماذا يُسأل ──
/// بطاقةُ حلّ المسائل تجعل الشاشةَ كلَّها زرَّ إيقافٍ للنطق: الشرحُ
/// دقيقتان، والطفلُ يسمع سطرين ثم يريد أن يكتب سؤالاً آخر، ولا زرَّ
/// إيقافٍ في مرمى إصبعه إلا الذي بدأه. وكان الحارس يعمل عند نزول
/// الإصبع — وهو أوّلُ ما يقع في التمرير أيضاً.
///
/// فكان الطفل ينزل بالصفحة ليقرأ بقيّةَ الجواب وهو يُنطق، فينقطع النطقُ
/// في منتصف الجملة. وهو يُمرّر ليتابع لا ليُسكت: القراءةُ والسماع معاً
/// هو ما تفعله الشاشة من أجله.
///
/// ── والفرقُ لا يُعرف إلا بعد رفع الإصبع ──
/// نزولُ الإصبع في اللمسة والتمرير واحد. فيُنتظر: إن تجاوز الإصبعُ
/// [kTouchSlop] فهو تمرير — وهي العتبةُ نفسها التي تفرّق بها Flutter
/// بين النقر والسحب، فلا يُخترع لها رقمٌ ثانٍ يخالفها. وإن رُفع في
/// موضعه فهي لمسةٌ تعني «اسكت».
///
/// ولا حدَّ للزمن: ضغطةٌ طويلةٌ في موضعها ليست تمريراً، وهي تعني
/// «اسكت» كما تعنيها السريعة.
class TapOrDrag {
  Offset? _start;
  bool _dragged = false;

  /// هل تحرّك الإصبعُ بما يكفي ليكون تمريراً؟ تُقرأ للاختبار والتشخيص.
  bool get dragged => _dragged;

  /// هل ثَمّ لمسةٌ جارية؟
  bool get active => _start != null;

  void down(Offset at) {
    _start = at;
    _dragged = false;
  }

  void move(Offset to) {
    final start = _start;
    if (start == null || _dragged) return;
    if ((to - start).distance > kTouchSlop) _dragged = true;
  }

  /// ترفع اللمسةَ وتقول: هل كانت لمسةً؟
  ///
  /// ويُقاس عند الرفع كما يُقاس عند الحركة: منصّةٌ لا تُرسل `move` بين
  /// النزول والرفع تترك السحبَ غيرَ ملحوظ لولا هذا.
  bool upIsTap(Offset at) {
    final start = _start;
    _start = null;
    if (start == null) return false;
    if (_dragged) return false;
    return (at - start).distance <= kTouchSlop;
  }

  void cancel() {
    _start = null;
    _dragged = false;
  }
}
