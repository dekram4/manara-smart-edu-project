/// حسابُ مكافأة الأيام المتتالية.
///
/// ── لماذا وحدةٌ مستقلّة ──
/// الرقمان — طولُ المتتالية التي تُكافأ، وعددُ جواهرها — مكتوبان في
/// الخادم في `studentProgress.ts`: `STREAK_MILESTONE` و`GEMS.streakBonus`.
/// وهما هنا أيضاً لأن الشاشة تُخبر الطالب بما ينتظره قبل أن يصل.
///
/// فلو افترقا لوعدت الشاشةُ بما لا يُصرَف: يقرأ الطفل «باقٍ لك يومان»
/// فيدخل يومين فلا يجد شيئاً، ولا في الشاشة ما يقول له لماذا. فعليهما
/// اختبارٌ يُثبت أنهما ما في الخادم.
class StudentStreak {
  const StudentStreak._();

  /// كم يوماً متتالياً يُكافأ.
  ///
  /// مطابقٌ لـ`STREAK_MILESTONE` في الخادم.
  static const milestone = 5;

  /// وكم جوهرةً تُمنح عند إكماله.
  ///
  /// مطابقٌ لـ`GEMS.streakBonus` في الخادم.
  static const bonusGems = 20;

  /// كم يوماً بقي حتى المكافأة التالية.
  ///
  /// ── والمكافأةُ دوريّة ──
  /// تُصرف عند الخامس والعاشر والخامس عشر، ولا شيء بينها. فمن أكمل خمسةً
  /// اليومَ ينتظر خمسةً أخرى — لا يوماً واحداً — وذلك ما يقوله هذا
  /// الحساب: `streak` من مضاعفات الخمسة يعود بخمسة لا بصفر.
  ///
  /// والصفرُ لا يُعاد أبداً: «باقٍ لك صفر» ليست عبارةً تُقال لطفل، ولا
  /// معنى لها — إمّا أن المكافأة صُرفت الآن، أو أن بينه وبينها أياماً.
  static int daysToBonus(int streak) {
    final safe = streak < 0 ? 0 : streak;
    final into = safe % milestone;
    return milestone - into;
  }

  /// هل صُرفت المكافأةُ في هذا اليوم بعينه؟
  ///
  /// تُستعمل للتهنئة لا للحساب: الخادم هو من يصرف، وهذه تقرأ ما صرفه.
  static bool earnedToday(int streak) => streak > 0 && streak % milestone == 0;

  /// نصيبُ المتتالية الحالية من الطريق إلى المكافأة، بين ٠ و١.
  ///
  /// ويُعرض ممتلئاً في يوم المكافأة لا فارغاً: الطفل الذي أكمل الخامس
  /// يستحقّ أن يرى الشريطَ تامّاً قبل أن يبدأ من جديد.
  static double progress(int streak) {
    if (streak <= 0) return 0;
    if (earnedToday(streak)) return 1;
    return (streak % milestone) / milestone;
  }
}
