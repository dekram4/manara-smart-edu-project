/// يبني حزمةَ المباراة [matchId]: عشرةُ أسئلةٍ عامّة، بابٌ بعد باب.
///
/// البناءُ مرّتين بالمعرّف نفسه يُخرج الحزمةَ نفسها حرفاً بحرف.
List<DuelQuestion> buildLocalDuelPack(
  String matchId, {
  int size = duelPackSize,
}) {
  final next = _seededRandom(duelPackSeed(matchId));

  // ── الأبوابُ بترتيب ظهورها في البنك ──
  // كما يفعل `Map` في الخادم: ترتيبُ الإدراج. فالخلطُ بعده يُخرج ما يُخرجه.
  final byCategory = <String, List<_Seed>>{};
  for (final seed in _seeds) {
    (byCategory[seed.category] ??= []).add(seed);
  }
  final order = _shuffled(byCategory.keys.toList(), next);
  final pools = {
    for (final entry in byCategory.entries)
      entry.key: _shuffled(entry.value, next),
  };

  final questions = <DuelQuestion>[];
  var turn = 0;
  while (questions.length < size) {
    final category = order[turn % order.length];
    turn += 1;
    final pool = pools[category]!;
    if (pool.isEmpty) {
      if (pools.values.every((list) => list.isEmpty)) break;
      continue;
    }
    final seed = pool.removeAt(0);
    final answer = seed.choices.first;
    final options = _shuffled(seed.choices, next);
    questions.add(
      DuelQuestion(
        id: '${seed.category}:${duelPackSeed(seed.prompt).toRadixString(36)}',
        category: seed.category,
        prompt: seed.prompt,
        options: options,
        answerAt: options.indexOf(answer),
      ),
    );
  }
  return questions;
}

/// بذرةٌ ثابتةٌ من نصّ — `packSeed` في الخادم.
int duelPackSeed(String text) {
  var seed = 7;
  for (final unit in text.codeUnits) {
    seed = (seed * 31 + unit) % 2147483647;
  }
  return seed;
}

/// نواةُ عشوائيةٍ ثابتة — `seededRandom` في الخادم.
double Function() _seededRandom(int seed) {
  var state = seed % 2147483647;
  if (state <= 0) state += 2147483646;
  return () {
    state = (state * 16807) % 2147483647;
    return (state - 1) / 2147483646;
  };
}

List<T> _shuffled<T>(List<T> items, double Function() next) {
  final copy = [...items];
  for (var i = copy.length - 1; i > 0; i -= 1) {
    final j = (next() * (i + 1)).floor();
    final swap = copy[i];
    copy[i] = copy[j];
    copy[j] = swap;
  }
  return copy;
}
