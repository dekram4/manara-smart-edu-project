/// المثنّى يحمل معنيين: «قدمان» قدمٌ واثنان — فمن قال «اثنين» أصاب، ومن قال
/// «قدمين» أصاب.
const Map<String, List<String>> _duals = {
  'عين': ['عينان', 'عينين', 'عيونين'],
  'اذن': ['اذنان', 'اذنين', 'اذنتين'],
  'يد': ['يدان', 'يدين', 'ايدين', 'ايدان'],
  'قدم': ['قدمان', 'قدمين', 'رجلين', 'رجلان'],
  'جناح': ['جناحان', 'جناحين'],
  'دراجه': ['عجلتان', 'عجلتين'],
  'تفاح': ['تفاحتان', 'تفاحتين'],
};

final Map<String, List<String>> _lookup = () {
  final map = <String, List<String>>{};
  _meanings.forEach((meaning, words) {
    for (final word in words) {
      map.putIfAbsent(normalizeSpoken(word), () => [meaning]);
    }
  });
  _duals.forEach((meaning, words) {
    for (final word in words) {
      map[normalizeSpoken(word)] = [meaning, '#2'];
    }
  });
  return map;
}();

/// كلماتُ كلِّ معنى بعد التوحيد: كلمةٌ لم تُعرف تُقارن بها بالسماع.
final Map<String, List<String>> _formsOf = {
  for (final entry in _meanings.entries) entry.key: [for (final w in entry.value) normalizeSpoken(w)],
};

/// كلمةٌ مما قيل أو كُتب: معناها إن عُرف، وإلا الكلمةُ نفسُها.
class _Token {
  const _Token(this.key, {required this.meaning});

  final String key;
  final bool meaning;
}

List<String>? _meaningOf(String word) {
  if (_lookup[word] case final found?) return found;
  // ‏«ال» وأخواتها، ثم حرفُ جرٍّ أو عطفٍ ملتصق: «بالباص»، «والقطة»، «للمدرسة».
  for (final prefix in const ['وال', 'بال', 'فال', 'كال', 'لل', 'ال', 'و', 'ب', 'ف', 'ل', 'ك']) {
    // ‏وحرفٌ واحدٌ ملتصق لا يُقصّ عن كلمةٍ قصيرة: «لاي» ليست «أي».
    if (word.startsWith(prefix) && word.length - prefix.length >= (prefix.length == 1 ? 3 : 2)) {
      final rest = word.substring(prefix.length);
      if (_lookup[rest] case final found?) return found;
      if (!prefix.startsWith('ال') && prefix.length == 1 && rest.startsWith('ال') && rest.length > 4) {
        if (_lookup[rest.substring(2)] case final found?) return found;
      }
    }
  }
  return null;
}

String _bare(String word) {
  for (final prefix in const ['وال', 'بال', 'فال', 'كال', 'لل', 'ال']) {
    if (word.startsWith(prefix) && word.length - prefix.length >= 2) return word.substring(prefix.length);
  }
  return word;
}

List<_Token> _tokens(String text) {
  final seen = <String>{};
  final out = <_Token>[];
  for (final word in normalizeSpoken(text).split(' ')) {
    if (word.isEmpty || _filler.contains(word)) continue;
    final meanings = _meaningOf(word);
    if (meanings != null) {
      for (final m in meanings) {
        if (seen.add(m)) out.add(_Token(m, meaning: true));
      }
      continue;
    }
    final bare = _bare(word);
    if (bare.length < 2 || _filler.contains(bare)) continue;
    if (seen.add(bare)) out.add(_Token(bare, meaning: false));
  }
  return out;
}

bool _hits(_Token said, _Token written) {
  if (said.meaning || written.meaning) {
    if (said.meaning && written.meaning) return said.key == written.key;
    // ‏كلمةٌ لم تُعرف وسُمعت قريبةً من إحدى كلمات المعنى («سلحفاا»).
    if (!said.meaning && said.key.length >= 4) {
      return (_formsOf[written.key] ?? const []).any((form) => form.length >= 4 && spokenWordsClose(said.key, form));
    }
    return false;
  }
  return spokenWordsClose(said.key, written.key);
}

/// درجةُ كلِّ خيار: كم غطّى الكلامُ من معناه (٠…١)، وكم كلمةً التقت.
class DuelVoiceScore {
  const DuelVoiceScore(this.index, this.coverage, this.hits);

  final int index;
  final double coverage;
  final int hits;

  double get value => coverage + hits * 0.01;
}

/// درجاتُ الخيارات التي التقى بها الكلام، الأعلى أوّلاً.
List<DuelVoiceScore> scoreDuelAnswer(String spoken, List<String> options) {
  final said = _tokens(spoken);
  if (said.isEmpty) return const [];
  final scores = <DuelVoiceScore>[];
  for (var i = 0; i < options.length; i++) {
    final written = _tokens(options[i]);
    if (written.isEmpty) continue;
    final hits = written.where((w) => said.any((s) => _hits(s, w))).length;
    if (hits == 0) continue;
    scores.add(DuelVoiceScore(i, hits / written.length, hits));
  }
  scores.sort((a, b) => b.value.compareTo(a.value));
  return scores;
}

/// الخيارُ الذي قصده الطفل — أو `null` إن لم يُفهم، أو تعادل خياران.
int? matchDuelAnswer(String spoken, List<String> options) {
  final scores = scoreDuelAnswer(spoken, options);
  if (scores.isEmpty) return null;
  if (scores.length == 1 || scores[0].value - scores[1].value >= 1e-9) return scores.first.index;
  // ‏تعادلٌ في المعنى («الماء» و«في الماء»): يُفصل بما قيل حرفاً إن كان أحدُهما
  // ‏فيه كاملاً — الأطولُ، فمن قال «في الماء» قصده لا «الماء».
  final top = scores.where((s) => (scores[0].value - s.value).abs() < 1e-9).toList();
  final said = ' ${normalizeSpoken(spoken)} ';
  final inside = [
    for (final s in top)
      if (normalizeSpoken(options[s.index]) case final o when o.isNotEmpty && said.contains(' $o ')) (s.index, o.length),
  ]..sort((a, b) => b.$2.compareTo(a.$2));
  if (inside.isEmpty || (inside.length > 1 && inside[0].$2 == inside[1].$2)) return null;
  return inside.first.$1;
}

/// والكلامُ لم ينتهِ بعد: يُؤخذ به في لحظته إن غطّى خياراً كاملاً ولم يمسّ غيرَه —
/// فلا ينتظر الطفلُ صمتاً يُنهي الاستماع والثواني تمضي.
int? earlyDuelAnswer(String spoken, List<String> options) {
  final scores = scoreDuelAnswer(spoken, options);
  if (scores.length != 1 || scores.single.coverage < 1) return null;
  return scores.single.index;
}
