import 'dart:convert';
import 'dart:io';

import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';

import 'package:manara_student/src/services/tracing_glyphs.dart';

Future<void> loadTracingFont() async {
  final bytes = File('assets/fonts/Tajawal-Bold.ttf').readAsBytesSync();
  final loader = FontLoader(tracingFontFamily)..addFont(Future.value(ByteData.sublistView(bytes)));
  await loader.load();
}

void main() {
  testWidgets('generate tracing glyph data', (tester) async {
    await tester.runAsync(() async {
      await loadTracingFont();
      final out = StringBuffer()
        ..writeln('// GENERATED by tool/generate_tracing_glyphs_test.dart — do not edit.')
        ..writeln('//')
        ..writeln('// مساراتُ تتبّع حروف الروضة وأرقامها: طرقُ tracing_routes.dart على هيكل assets/fonts/Tajawal-Bold.ttf.')
        ..writeln('// انظر precomputedTracingShape في tracing_glyphs.dart.')
        ..writeln()
        ..writeln('const tracingGlyphData = <String, String>{');
      for (final item in kindergartenTracingItems) {
        final shape = await routedTracingShape(item);
        expect(shape, isNotNull, reason: 'no shape for ${item.text}');
        final json = jsonEncode(shape!.toJson()).replaceAll(r'$', r'\$');
        final key = tracingGlyphKey(item);
        out.writeln("  '$key': '$json',");
      }
      out.writeln('};');
      File('lib/src/services/tracing_glyph_data.g.dart').writeAsStringSync(out.toString());
    });
  });
}
