def fetch(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'manara-student-build'})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def tanzil():
    raw = fetch(TANZIL).decode('utf-8')
    verses, notice = {}, []
    for line in raw.splitlines():
        if line.startswith('#'):
            notice.append(line)
            continue
        if not line.strip():
            continue
        sura, aya, text = line.split('|', 2)
        verses[(int(sura), int(aya))] = text
    return verses, notice


def clean(text):
    return unicodedata.normalize('NFC', text).replace('ٰ', '')


BASMALA = clean('بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ')


def surah_verses(verses, sura):
    out, aya = [], 1
    while (sura, aya) in verses:
        text = clean(verses[(sura, aya)])
        if aya == 1 and text.startswith(BASMALA + ' '):
            text = text[len(BASMALA) + 1:]
        assert "'" not in text and '\\' not in text, (sura, aya)
        out.append(text)
        aya += 1
    return out


def write_dart(verses, notice):
    lines = [
        '// GENERATED by tool/build_juz_amma.py — do not edit by hand.',
        '//',
        '// Quran text: Tanzil Project, simple-plain edition — https://tanzil.net',
        '// Processed exactly as the surahs in quran_recitation.dart: Unicode NFC,',
        '// superscript alif (U+0670) dropped, basmala recited as its own step.',
        '//',
    ]
    lines += ['// ' + line.lstrip('#').rstrip() for line in notice if line.strip('#').strip()]
    lines += [
        '',
        "part of 'quran_recitation.dart';",
        '',
        '/// بقيّةُ جزء عمّ (النبأ إلى الماعون)، بترتيب الحفظ من آخر المصحف.',
        'const juzAmmaSurahs = <QuranSurah>[',
    ]
    total = 0
    for sura, sid, name, _ in SURAHS:
        texts = surah_verses(verses, sura)
        total += len(texts)
        lines.append(f"  QuranSurah(id: '{sid}', name: '{name}', verses: [")
        lines += [f"    '{t}'," for t in texts]
        lines.append('  ]),')
    lines.append('];')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(OUT.name, total, 'verses')
    return total


def download_audio(verses):
    QURAN_AUDIO.mkdir(parents=True, exist_ok=True)
    count = size = 0
    for sura, sid, _, _ in SURAHS:
        for aya in range(1, len(surah_verses(verses, sura)) + 1):
            path = QURAN_AUDIO / f'{sid}_{aya}.mp3'
            if not path.exists():
                path.write_bytes(fetch(EVERYAYAH.format(sura=sura, aya=aya)))
            count += 1
            size += path.stat().st_size
    print(count, 'recitation clips,', size // 1024, 'KB')


async def record_names():
    NAME_AUDIO.mkdir(parents=True, exist_ok=True)
    for _, sid, _, spoken in SURAHS:
        path = NAME_AUDIO / f'surah_{sid}.mp3'
        await edge_tts.Communicate(spoken, VOICE['voice'], pitch=VOICE['pitch'], rate=VOICE['rate']).save(str(path))
    print(len(SURAHS), 'name clips')


if __name__ == '__main__':
    verses, notice = tanzil()
    write_dart(verses, notice)
    download_audio(verses)
    asyncio.run(record_names())
