"""Adds the rest of Juz' 'Amma (surahs 78–107) to «أبطال التسميع».

    py tool/build_juz_amma.py

Text — Tanzil Project, `simple-plain` edition (https://tanzil.net). The eight
short surahs already in the app are exactly this edition after three steps,
checked verse by verse: Unicode NFC, the superscript alif (U+0670) dropped,
and the basmala taken off the first verse (the game recites it as its own
step before the surah). The same three steps are applied here, so all 37
surahs read the same way. Writes lib/src/services/quran_juz_amma.g.dart,
which carries Tanzil's notice as its license requires.

Recitation — Mahmoud Khalil Al-Husary, murattal, from everyayah.com
(`Husary_64kbps`): the very files the eight surahs already use, byte for
byte. One file per verse → assets/audio/quran/<id>_<n>.mp3.

Surah names → assets/audio/surah_names/surah_<id>.mp3, in the app's voice
(see build_tracing_voices.py), said like the existing ones: «سورة …».
"""

