/**
 * يُبقي المرجعَ القديم إن لم يتغيّر المحتوى.
 *
 * ── لماذا هذه موجودة ──
 * شاشاتُ اللوحات تقرأ جداولَها من `localStorage` بـ`JSON.parse` على فواصلَ
 * زمنية. وكلُّ قراءةٍ تُخرج كائناتٍ **جديدةَ الهويّة** ولو لم يتغيّر حرفٌ
 * واحد. ولا يقارن React المحتوى بل الهويّة، فيرى حالاً جديدةً كلَّ مرّة:
 *
 *   • أرخصُ أثرٍ: إعادةُ بناءِ اللوحة كلِّها كلَّ خمس ثوانٍ بلا داعٍ.
 *   • وأغلاه: حلقةٌ لا تنتهي إن كانت تلك الحالُ في قائمة تبعيّات أثرٍ يكتبها
 *     — يكتب فتتغيّر الهويّة فيُعاد تشغيله فيكتب. وهو ما جمّد بوابةَ وليّ
 *     الأمر عند فتح ملفّ ابنٍ: الحالُ `activeChild` كانت تبعيّةً وكاتباً.
 *
 * فتُمرَّر القراءةُ من هنا: إن كان محتواها كمحتوى الحالّ عاد المرجعُ القديم،
 * فيتخطّى React الإعادةَ ولا تتحرّك تبعيّة.
 *
 * ── والمقارنةُ بالتسلسل، وهذا مقصود ──
 * القيمُ هنا أتت من `JSON.parse` أصلاً: لا دوالَّ فيها ولا مراجعَ دوريّة،
 * وترتيبُ مفاتيحها ثابتٌ لأنّ مصدرَها نصٌّ واحد. فمقارنةٌ عميقةٌ مكتوبةٌ بيدٍ
 * لا تُضيف صحّةً وتُضيف شيفرةً تُصان. وثمنُها على جدولٍ من عشراتِ الصفوف
 * أرخصُ بمراتبَ من إعادةِ بناءِ شجرةِ لوحةٍ كاملة.
 *
 * وما لا يُسلسَل — `undefined` أو دورةُ مراجع — يُعدّ مختلفاً فتعود القيمةُ
 * الجديدة. وهو الجانبُ الآمن: عرضٌ زائدٌ لا عرضٌ ساقط.
 */
export function keepIfSame<T>(current: T, next: T): T {
  if (current === next) return current;
  return serialize(current) === serialize(next) ? current : next;
}

/** تسلسلٌ لا يرفع: ما تعذّر تسلسلُه يُعدّ فريداً فيُقرأ مختلفاً. */
function serialize(value: unknown): string {
  try {
    return JSON.stringify(value) ?? '\u0000undefined';
  } catch {
    return `\u0000unserializable:${Math.random()}`;
  }
}
