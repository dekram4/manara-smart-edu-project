/**
 * يُزيل ترميز LaTeX والرموز الرياضية من نصّ درس.
 *
 * النصوص تمرّ بأدواتٍ تلفّ ما تحسبه رياضياً بـ `$...$` أو `\(...\)`،
 * فيصل إلى الطالب سطرٌ فيه علامةُ دولارٍ قبل عددٍ ولا معنى لها. والتنقية
 * هنا — في وحدة المنهج — لا عند العرض: ما يُحفظ في قاعدة البيانات هو ما
 * يُقرأ، ولا طبقةَ تنظيفٍ بينهما تُنسى يوماً.
 *
 * ويُشارك فيها المناهج كلّها: قاعدةٌ واحدة لا تفترق بين مادةٍ وأخرى.
 */
export function stripMathMarkup(text) {
  return String(text ?? "")
    .replace(/\$\$([\s\S]*?)\$\$/g, "$1")
    .replace(/\$([^$\n]*?)\$/g, "$1")
    .replace(/\\\(([\s\S]*?)\\\)/g, "$1")
    .replace(/\\\[([\s\S]*?)\\\]/g, "$1")
    .replace(/\\(?:text|mathrm|mathbf|textbf|mbox)\{([^}]*)\}/g, "$1")
    .replace(/\$/g, "")
    .replace(/[ \t]+$/gm, "");
}
