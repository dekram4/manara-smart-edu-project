/** الدروس بعد تنقية نصوصها — وهي ما يُقرأ ويُكتب، لا الخام. */
export const LESSONS = Object.fromEntries(
  Object.entries(RAW_LESSONS).map(([number, lesson]) => [
    number,
    { ...lesson, text: stripMathMarkup(lesson.text) },
  ]),
);

/** الدروس بترتيبها، كلٌّ مع فصله ووحدته — وهو ما يُكتب في الجدولين. */
export function curriculumRows() {
  const rows = [];
  for (const group of UNITS) {
    for (const number of group.lessons) {
      const lesson = LESSONS[number];
      if (!lesson) throw new Error(`لا نصّ للدرس ${number}`);
      rows.push({
        number,
        term: group.term,
        unit: group.unit,
        name: lesson.name,
        text: lesson.text,
      });
    }
  }
  return rows;
}
