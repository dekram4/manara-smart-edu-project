/** نصُّ الصورة منظّفاً، أو `null` إن لم يُقرأ منها شيءٌ يُعتدّ به. */
export function cleanTranscription(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const text = raw
    .replace(/^```[a-z]*\s*/i, "")
    .replace(/```\s*$/, "")
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
    .join("\n")
    .trim();
  if (text.length < 2 || /^غير\s*واضح/.test(text)) return null;
  return text.slice(0, 2000);
}
