import { createHash } from "node:crypto";

/**
 * سياسةُ «حل المسائل»: ما يُجاب عنه، وما لا يُحفظ في الذاكرة الدائمة.
 *
 * ── لماذا وُسِّع النطاق ──
 * كان النموذج يُؤمر: «إن لم تجد الإجابة في نصّ الدرس فقل: هذا السؤال ليس
 * من ضمن الدرس». ونصُّ الدرس شرحٌ لا بنكُ أسئلة، فرُدَّ طفلٌ سأل «ما منزلة
 * الرقم ٢ في العدد ٥٢٣٠» في درس المنازل لأن العدد نفسه لم يرد في النصّ.
 * والسؤالُ من صميم الدرس. فالحدُّ الآن مهاراتُ المادة وموضوعُ الدرس لا
 * حروفُ النصّ، والاعتذارُ لما خرج عن التعليم وحده.
 *
 * ── ولماذا يُعرَف الرفضُ القديم ──
 * الذاكرةُ دائمة: رفضٌ حُفظ يُعاد على كل طفلٍ يسأل السؤالَ نفسه إلى الأبد.
 * وقد حُفظت رفوضٌ فعلاً قبل هذا التغيير. فالرفضُ يُعامَل إخفاقاً عند
 * القراءة — فيُولَّد جوابٌ صحيح ويُكتب فوقه بالمفتاح نفسه — ولا يُكتب أصلاً.
 */

/** ما يُقال للنموذج عن نطاق ما يجيب عنه. */
export const SOLVER_SCOPE_INSTRUCTION =
  "نصُّ الدرس مرجعُك الأول، لا حدودُ ما تجيب عنه. " +
  "فإن كان السؤال من مهارات المادة أو موضوع الدرس — ولو لم يرد بنصّه أو بأرقامه في الدرس، " +
  "مثل تحديد منزلة رقمٍ في عددٍ ضمن مئات الألوف، أو مسألةٍ حسابيةٍ مشابهةٍ لما في الدرس — " +
  "فأجب عنه بوضوحٍ ودقّة كما يشرحه معلّم المادة، وتحقّق من الحساب قبل أن تكتب الناتج. " +
  "ولا تعتذر إلا إن كان السؤال لا علاقة له بالتعليم أو غير لائقٍ بطفل؛ " +
  "وحينها قل بلطف إنك هنا لتساعده في دروسه، واقترح عليه سؤالاً من مادته. " +
  "ولا تقل أبداً إن السؤال ليس من ضمن الدرس.";

/**
 * عباراتُ الرفض القديم — بالفصحى وبالدارجة — بعد تطبيعٍ يُسقط التشكيل
 * والهمزات، فتُعرف وإن كُتبت بأيّ صورة.
 */
const REFUSALS = [
  "ليس من ضمن الدرس",
  "ليس ضمن الدرس",
  "مو من ضمن الدرس",
  "مو ضمن الدرس",
  "ليس من الدرس",
  "خارج الدرس ولا استطيع",
  "لا استطيع الاجابه عليه",
  "لا استطيع الاجابه عنه",
  "ما اقدر اجاوب",
];

function flatten(text: string): string {
  return text
    .replace(/[ً-ٰٟـ]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ");
}

/**
 * هل هذه الإجابةُ رفضٌ بحجّة أن السؤال ليس من الدرس؟
 *
 * يُقاس أوّلُ الإجابة وحده: الرفضُ جملةٌ قصيرة تبدأ بها، وشرحٌ طويلٌ صحيح
 * قد يذكر «الدرس» في وسطه فلا يُردّ بسببه.
 */
export function isRefusalAnswer(answer: unknown): boolean {
  if (typeof answer !== "string") return false;
  const head = flatten(answer.trim()).slice(0, 160);
  if (!head) return false;
  return REFUSALS.some((phrase) => head.includes(phrase));
}

/**
 * نصُّ مفتاحٍ لصورةٍ لم يُقرأ ما فيها: بصمتُها.
 *
 * كانت تُجاب ولا تُحفظ، لأن المفتاح يُبنى من نصّ الصورة. والصورةُ نفسها
 * إن أُرسلت ثانيةً — طفلٌ يعيد المحاولة، أو زميلٌ أُرسلت إليه — تُصاب
 * ببصمتها. ولا تُقاس بالمعنى: لا نصَّ لها يُقاس.
 */
export function imageKeyText(fingerprint: string, typed: string): string {
  const asked = typed.trim();
  return `صوره ${fingerprint}${asked ? ` ${asked}` : ""}`;
}

/**
 * الأعمدةُ المقروءة في صفّ الذاكرة — ما يعرضه `solved_questions_cache`.
 *
 * أُضيفت إلى `ai_qa_cache` في الإنتاج خارج الكود، والخادمُ يكتب في `data`
 * وحده، فبقيت فارغةً في كل صفّ وبدا المحفوظُ كأنه لم يُحفظ. ونقيّةٌ هنا
 * لتُختبر، ويستعملها الخادمُ عند الحفظ وسكربتُ الإكمال للصفوف القديمة.
 *
 * `question_hash`: بصمةُ المفتاح (الدرسُ والسؤالُ مطبَّعاً) — السؤالان
 * اللذان يلتقيان على مفتاحٍ واحد لهما بصمةٌ واحدة.
 */
export function cacheReadableColumns(
  key: string,
  lessonId: string,
  question: string,
  answer: string,
  domain?: string,
): { question_hash: string; question_text: string; answer_json: Record<string, string>; domain: string } {
  return {
    question_hash: createHash("sha256").update(key).digest("hex"),
    question_text: question,
    answer_json: { answer, question, lessonId },
    domain: (domain ?? "").trim() || "problem_solver",
  };
}
