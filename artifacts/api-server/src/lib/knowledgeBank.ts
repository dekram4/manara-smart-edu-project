/**
 * معرّفُ السؤال الثابت: بابُه وبصمةُ نصّه — على صيغة البنك الأوّل
 * (`general:ivp27c`) ليُمنع تكرارُه في الحزمة وبين المباريات.
 */
export function knowledgeId(seed: Pick<KnowledgeSeed, "category" | "prompt">): string {
  let hash = 7;
  for (let i = 0; i < seed.prompt.length; i += 1) {
    hash = (hash * 31 + seed.prompt.charCodeAt(i)) % 2147483647;
  }
  return `${seed.category}:${hash.toString(36)}`;
}

/** هل [value] بابٌ من أبواب المعرفة العامّة؟ */
export function isKnowledgeCategory(value: string): value is KnowledgeCategory {
  return (KNOWLEDGE_CATEGORIES as readonly string[]).includes(value);
}
