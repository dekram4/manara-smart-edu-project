/**
 * تنقيةُ نصّ الإجابة من التشكيل.
 *
 * ── لماذا في الخادم أيضاً، والتطبيق ينقّي قبل النطق ──
 * مصفاةُ التطبيق تحرس ما يُنطق وحده — `speakableText` تُنادى في طريق
 * الصوت لا في طريق العرض. والإجابةُ تُقرأ مكتوبةً كما تُسمع، فالتشكيل
 * يبقى في الشاشة وإن سقط من النطق.
 *
 * ثم إن الطلب يمنع التشكيل، والنموذج يمتثل في الغالب لا دائماً: عبارةٌ
 * منقولةٌ من نصّ الدرس تأتي مشكولةً كما في الكتاب، وقراءةُ الصورة تنقل
 * ما رأت. فالطلبُ نيّة، وهذه حراسة.
 *
 * ── ويُنقّى ما يُحفظ لا ما يُعرض وحده ──
 * التنقيةُ قبل الحفظ، فالذاكرةُ تحمل النصّ نظيفاً ولا يُعاد تنقيتُه على
 * كل إصابة. وما حُفظ قبل هذا مشكولاً يُنقّى عند قراءته.
 */

/**
 * علاماتُ التشكيل والتطويل.
 *
 * `064B-065F` التنوينُ والحركاتُ والشدّةُ والسكون وما أُلحق بها، و`0670`
 * ألفُ الوصل الصغيرة، و`06D6-06ED` علاماتُ الوقف القرآنية — تصل من قارئ
 * الصورة حين يكون الكتابُ مشكولاً. و`0640` التطويل، وهو حرفُ مطٍّ لا
 * علامة، فلولا ذكرُه لبقي «مرحبـــا».
 *
 * وهو المدى نفسه في `speakableText` بالتطبيق: ما يُقرأ وما يُسمع واحد.
 */
const DIACRITICS = /[ً-ٰٟۖ-ۭـ]/g;

/**
 * النصُّ بلا تشكيل.
 *
 * ويُحذف الحرفُ ولا يُستبدل بمسافة: الحركةُ علامةٌ فوق حرفها لا بينه
 * وبين ما يليه، فمسافةٌ مكانَها تقطع الكلمة — «أوّلاً» تصير «أو» و«لا»،
 * أي نقيضَ معناها.
 */
export function stripDiacritics(value: unknown): string {
  return typeof value === "string" ? value.replace(DIACRITICS, "") : "";
}

/**
 * التشكيلُ الخفيف: ما يمنع اللبس ويُبقي النطقَ متّصلاً.
 *
 * ── لماذا لا الكاملُ ولا لا شيء ──
 * النصُّ بلا تشكيلٍ يلتبس على محرّك النطق — «علم» عِلمٌ أم عَلَّم؟ — فينطقه
 * خطأً. والمشكولُ كاملاً يُقرأ بالإعراب على أواخر الكلمات، فيُسمع متقطّعاً
 * «الخَ-لِي-يَ-ةُ» كأنه درسُ نحو. فيُبقى ما يحسم النطق ويُسقط ما يقطعه:
 *
 *   • الشدّةُ أينما كانت — «حلّ» و«علّم».
 *   • حركاتُ وسط الكلمة — «فَهِمت» و«يُفرِّق».
 *   • وتسقط حركةُ آخر الكلمة وسكونُه — الإعراب — والتنوينُ كلُّه، فتُقرأ
 *     الكلمةُ موقوفاً عليها كما يتكلّم الناس.
 *
 * والتطويلُ وعلاماتُ الوقف القرآنية تسقط كما في [stripDiacritics].
 */
export function lightDiacritics(value: unknown): string {
  if (typeof value !== "string") return "";
  return value
    // التطويلُ وألفُ الوصل الصغيرة وعلاماتُ الوقف القرآنية.
    .replace(/[ـٰۖ-ۭ]/g, "")
    // آخرُ الكلمة: حرفٌ تتبعه علاماتٌ ثم ما ليس حرفاً عربياً ولا علامة.
    // تبقى الشدّةُ منها وحدها.
    .replace(
      /([ء-ي])([ً-ْ]+)(?![ء-يً-ْ])/g,
      (_, letter: string, marks: string) => letter + (marks.includes("ّ") ? "ّ" : ""),
    )
    // والتنوينُ حيث بقي، وما أُلحق بالحركات من علاماتٍ نادرة.
    .replace(/[ً-ٍٓ-ٟ]/g, "");
}
