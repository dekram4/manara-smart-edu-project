export interface KgQuestion {
  id: string;
  number: number;
  category: string;
  prompt: string;
  answer: string;
}

export const KG_QUESTIONS: readonly KgQuestion[] = ROWS.map(([number, category, prompt, answer]) => ({
  id: kgQuestionId(number),
  number,
  category,
  prompt,
  answer,
}));

export function kgQuestionId(number: number): string {
  return `kg_${String(number).padStart(3, "0")}`;
}

/** بذرةٌ ثابتةٌ من نصّ (FNV-1a). */
function seedOf(text: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash >>> 0;
}

/** مولّدٌ صغيرٌ ببذرة (mulberry32): الأرقامُ نفسُها للبذرة نفسِها. */
function random(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffled<T>(items: readonly T[], next: () => number): T[] {
  const list = [...items];
  for (let i = list.length - 1; i > 0; i--) {
    const j = Math.floor(next() * (i + 1));
    [list[i], list[j]] = [list[j], list[i]];
  }
  return list;
}

const YES_NO = ["نعم", "لا"];

/**
 * خياراتُ سؤال: جوابُه وثلاثةُ مشتّتاتٍ من أجوبة بابه (ثم من غيره إن قلّت).
 * وسؤالُ «نعم/لا» خياراه «نعم» و«لا» وحدهما.
 */
function optionsFor(question: KgQuestion, next: () => number): string[] {
  if (YES_NO.includes(question.answer)) return shuffled(YES_NO, next);
  const pool = (same: boolean) =>
    shuffled(
      [...new Set(KG_QUESTIONS
        .filter((q) => (q.category === question.category) === same)
        .map((q) => q.answer))]
        .filter((answer) => answer !== question.answer && !YES_NO.includes(answer)),
      next,
    );
  const distractors = [...pool(true), ...pool(false)].slice(0, 3);
  return shuffled([question.answer, ...distractors], next);
}

/** حزمةُ مباراةِ روضةٍ من معرّفها: عشرةُ أسئلةٍ مختلفة بخياراتها. */
export function kgPackFor(matchId: string, size: number = DUEL_PACK_SIZE): DuelPack {
  const next = random(seedOf(`kg:${matchId}`));
  const picked = shuffled(KG_QUESTIONS, next).slice(0, Math.min(size, KG_QUESTIONS.length));
  const questions: DuelQuestion[] = picked.map((question) => {
    const options = optionsFor(question, next);
    return {
      id: question.id,
      category: "general",
      prompt: question.prompt,
      options,
      answerAt: options.indexOf(question.answer),
    };
  });
  return { version: DUEL_PACK_VERSION, builtAt: "", questions };
}
